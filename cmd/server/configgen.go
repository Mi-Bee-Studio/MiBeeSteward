package main

import (
	"crypto/rand"
	"encoding/base64"
	"fmt"
	"os"
	"path/filepath"
)

// minimalConfigTemplate is the first-run config generated when the -config
// path does not exist (#682): deliberately tiny — a random jwt_secret, an
// empty admin password (the browser first-run setup creates it), defaults
// for everything else. The full reference stays in configs/config.example.yaml.
//
// Security invariants: no master_key (v3 credential vault stays disabled
// until the user opts in), reserved-range scan targets remain rejected
// (allow_reserved_targets is never set here).
const minimalConfigTemplate = `# Generated by mibee-steward on first run: the configured config file
# was missing. Edit freely — the full option reference is
# configs/config.example.yaml in the repository (or the release tarball).
server:
  host: "0.0.0.0"
  port: 8080

auth:
  # Randomly generated for this instance. Treat it as private; rotating it
  # logs everyone out.
  jwt_secret: %q
  # Empty = the first visit to the UI opens the browser first-run setup
  # that creates the admin password.
  initial_admin_password: ""
`

// ensureConfigFile generates a minimal first-run config at path when it does
// not exist, returning true. An existing file is left byte-for-byte alone —
// even a broken one — so user- and installer-written configs are never
// silently rewritten.
func ensureConfigFile(path string) (bool, error) {
	switch _, err := os.Stat(path); {
	case err == nil:
		return false, nil
	case !os.IsNotExist(err):
		return false, fmt.Errorf("stat config: %w", err)
	}

	// 32 random bytes, base64 = 44 chars: comfortably past the 32-char
	// minimum and never the rejected placeholder value.
	secret := make([]byte, 32)
	if _, err := rand.Read(secret); err != nil {
		return false, fmt.Errorf("read random secret: %w", err)
	}

	body := fmt.Sprintf(minimalConfigTemplate, base64.StdEncoding.EncodeToString(secret))
	if dir := filepath.Dir(path); dir != "" {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return false, fmt.Errorf("create config directory %s: %w", dir, err)
		}
	}
	// 0600: the file carries the instance's jwt_secret.
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		return false, fmt.Errorf("write config: %w", err)
	}
	return true, nil
}

// generateIfMissing is runCLI's #682 front step: generate the config when
// missing and tell the operator where it landed (slog is not initialized
// yet — it needs the config — so the notice goes to stdout, which systemd
// captures into the journal). The error wraps the config path so the CLI
// front door prints an actionable message.
func generateIfMissing(path string) (bool, error) {
	generated, err := ensureConfigFile(path)
	if err != nil {
		return false, fmt.Errorf("config file %s is missing and generating a minimal one failed: %w", path, err)
	}
	if generated {
		fmt.Printf("mibee-steward: no config file found — generated a minimal one at %s\n", path)
		fmt.Printf("mibee-steward: open http://<this-host>:8080 in a browser to complete the first-run admin setup\n")
	}
	return generated, nil
}
